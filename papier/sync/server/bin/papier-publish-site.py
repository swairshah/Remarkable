def read_json(path, default=None):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def frontmatter_title(md_path):
    try:
        with open(md_path, "r", encoding="utf-8") as f:
            lines = f.read().split("\n")
    except OSError:
        return None
    if not lines or lines[0].strip() != "---":
        return None
    for line in lines[1:40]:
        if line.strip() == "---":
            break
        if line.startswith("title:"):
            return line[6:].strip().strip('"').strip("'")
    return None


def markdown_html(md_path):
    args = ["pandoc", md_path, "--from",
            "markdown+smart+tex_math_dollars+tex_math_single_backslash+tex_math_double_backslash+yaml_metadata_block",
            "--to", "html5", "--mathml", "--wrap=none"]
    res = subprocess.run(args, capture_output=True, text=True)
    if res.returncode != 0:
        raise SystemExit("pandoc failed for %s: %s" % (md_path, res.stderr.strip()))
    return res.stdout


def day(iso):
    return html.escape((iso or "")[:10])


def build_post(repo, out, base, meta):
    pid = meta["id"]
    src = os.path.join(repo, "posts", pid)
    dst = os.path.join(out, "posts", pid)
    os.makedirs(dst, exist_ok=True)
    title = frontmatter_title(os.path.join(src, "post.md")) or meta.get("title") or pid
    body_html = markdown_html(os.path.join(src, "post.md"))

    assets_src = os.path.join(src, "assets")
    if os.path.isdir(assets_src):
        shutil.copytree(assets_src, os.path.join(dst, "assets"), dirs_exist_ok=True)

    published, updated = meta.get("published"), meta.get("updated")
    dates = f"Published {day(published)}"
    if updated and updated[:10] != (published or "")[:10]:
        dates += f" · updated {day(updated)}"
    body = (
        f'      <header class="profile-header page-header">\n        <h1>{html.escape(title)}</h1>\n      </header>\n'
        f'      <p class="post-dates">{dates}</p>\n'
        f'      <article class="post-body">\n{body_html}      </article>\n'
        f'      <nav class="nav-bottom" aria-label="Secondary navigation">\n        <a href="{base}">All posts</a>\n        <a href="/about.html">About</a>\n      </nav>\n'
    )
    with open(os.path.join(dst, "index.html"), "w", encoding="utf-8") as f:
        f.write(page(title, body, base))
    return {"id": pid, "title": title, "published": published, "updated": updated}


def build_index(out, base, posts):
    posts = sorted(posts, key=lambda p: (p.get("updated") or p.get("published") or "", p["id"]), reverse=True)
    if posts:
        items = "\n".join(
            f'        <li><a href="{base}posts/{html.escape(p["id"])}/">{html.escape(p["title"])}</a>'
            f'<time datetime="{day(p.get("updated") or p.get("published"))}">{day(p.get("updated") or p.get("published"))}</time></li>'
            for p in posts
        )
        listing = f'      <ul class="post-list">\n{items}\n      </ul>\n'
    else:
        listing = '      <p class="about-copy">Nothing published yet.</p>\n'
    body = (
        f'      <header class="profile-header page-header">\n        <h1>{html.escape(SITE_NAME)} / {SECTION}</h1>\n      </header>\n'
        f'      <p class="about-copy">Notes, essays, diagrams, and sketches from my notebook.</p>\n'
        + listing
    )
    with open(os.path.join(out, "index.html"), "w", encoding="utf-8") as f:
        f.write(page(SECTION, body, base))


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    repo, out = argv[1], argv[2]
    base = "/"
    i = 3
    while i < len(argv):
        if argv[i] == "--base-url":
            base = argv[i + 1]; i += 2
        else:
            print("unknown argument: " + argv[i], file=sys.stderr)
            return 2
    if not base.endswith("/"):
        base += "/"

    posts_dir = os.path.join(repo, "posts")
    ids = sorted(d for d in os.listdir(posts_dir)) if os.path.isdir(posts_dir) else []
    metas = []
    for pid in ids:
        meta = read_json(os.path.join(posts_dir, pid, "meta.json"))
        if not meta or not os.path.isfile(os.path.join(posts_dir, pid, "post.md")):
            continue
        meta["id"] = pid
        metas.append(meta)

    # Rebuild from scratch into a sibling then swap: a half-written tree is
    # never what rsync sees.
    tmp = out.rstrip("/") + ".tmp"
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(tmp)
    with open(os.path.join(tmp, "writing.css"), "w", encoding="utf-8") as f:
        f.write(CSS)
    posts = [build_post(repo, tmp, base, m) for m in metas]
    build_index(tmp, base, posts)
    shutil.rmtree(out, ignore_errors=True)
    os.rename(tmp, out)
    print(json.dumps({"posts": len(posts)}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
